"""Write installer/registry.iss: the right-click entry for every file type
Cerclic handles, exactly as the app writes it (cerclic/win/shell.py).

Run after changing the supported extensions; a test checks it is up to date.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from cerclic.paths import SUPPORTED_EXTS  # noqa: E402

OUT = os.path.join(ROOT, "installer", "registry.iss")


def render() -> str:
    lines = ["; Generated by scripts/gen_installer_registry.py, do not edit by hand.",
             "; Right-click entry \"Cerclic\" for each supported file type (per user)."]
    for ext in sorted(SUPPORTED_EXTS):
        key = rf"Software\Classes\SystemFileAssociations\{ext}\shell\Cerclic"
        lines += [
            f'Root: HKCU; Subkey: "{key}"; Flags: uninsdeletekey',
            f'Root: HKCU; Subkey: "{key}"; ValueType: string; ValueName: "MUIVerb"; ValueData: "Cerclic"',
            f'Root: HKCU; Subkey: "{key}"; ValueType: string; ValueName: "Icon"; ValueData: "{{app}}\\Cerclic.exe,0"',
            f'Root: HKCU; Subkey: "{key}"; ValueType: string; ValueName: "Position"; ValueData: "Top"',
            f'Root: HKCU; Subkey: "{key}"; ValueType: string; ValueName: "MultiSelectModel"; ValueData: "Player"',
            f'Root: HKCU; Subkey: "{key}\\command"; ValueType: string; ValueName: ""; '
            f'ValueData: """{{app}}\\CerclicOpen.exe"" ""%1"""',
        ]
    return "\r\n".join(lines) + "\r\n"


if __name__ == "__main__":
    with open(OUT, "w", encoding="utf-8", newline="") as f:
        f.write(render())
    print("wrote", OUT)
